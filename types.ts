export interface SurveyData {
  // Demographic
  age: number;
  gender: string;
  gradeLevel: string;

  // Behavioral
  dailyUsageHours: number;
  phoneChecksPerDay: number;
  gamingHours: number;
  screenTimeBeforeBed: number; // minutes
  mostUsedAppCategory: string; // Social, Gaming, Education, Entertainment

  // Psychological (Scale 1-10)
  anxietyLevel: number;
  depressionLevel: number;
  selfEsteem: number;
  familyCommunication: number;

  // Personality Traits (Big 5) - Scale 1-10
  openness: number;
  conscientiousness: number;
  extraversion: number;
  agreeableness: number;
  neuroticism: number;

  // Academic / Lifestyle
  academicPerformance: number; // GPA or 0-100 scale
  exerciseHours: number;
  socialInteractions: number; // Hours per week offline
}

export enum AddictionLevel {
  LOW = 'Low',
  MODERATE = 'Moderate',
  HIGH = 'High'
}

export interface TrainingLog {
  epoch: number;
  loss: number;
}

export interface HistoryLog {
  day: string;
  score: number;
  usageHours: number;
  anxiety: number;
  sleep: number; // calculated from bedtime usage inverse or just a metric
}

export interface AnalysisResult {
  score: number; // 0-100 (Predicted by DL Model)
  level: AddictionLevel;
  academicImpactPrediction: string; // Generated by AI
  riskFactors: string[];
  recommendations: string[];
  psychologicalProfile: {
    stress: number;
    escapism: number;
    socialHealth: number;
  };
}